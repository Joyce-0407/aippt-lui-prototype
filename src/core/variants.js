// 兜底变换（语料未命中时）
export const EXPAND_SUFFIX = [
  '，这一细节在考古报告中亦有详载',
  '，其背后是一个时代的工艺巅峰',
  '，至今仍为研究者津津乐道',
];

export function rewriteText(text, mode, setText) {
  if (setText) return setText;
  const v = VARIANTS[text] || {};
  const firstClause = text.split(/[，、；。]/)[0] + (text.includes('。') ? '。' : '');
  switch (mode) {
    case 'short': return v.short || firstClause;
    case 'formal': return v.formal || text;
    case 'alt': return v.alt || v.polish || text;
    case 'casual': return v.casual || `简单来说，${firstClause}`;
    case 'expand': return v.expand || text.replace(/。?$/, EXPAND_SUFFIX[Math.floor(Math.random() * EXPAND_SUFFIX.length)] + '。');
    case 'polish':
    default: return v.polish || v.formal || text;
  }
}
